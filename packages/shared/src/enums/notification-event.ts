/** Тип события для уведомлений. У каждого — своя строка
 *  notification_event_preference на customer'а. */
export enum NotificationEvent {
  /** Скоро спишется подписка (UPCOMING_CHARGE) — единственный воркер MVP. */
  UPCOMING_CHARGE = 1,
  /** Заканчивается триал подписки — воркер появится позже. */
  TRIAL_END = 2,
  /** Продление тарифа Sub0 — воркер появится позже. */
  PLAN_RENEWAL = 3,
  /** Месячная сводка расходов — воркер появится позже. */
  MONTHLY_REPORT = 4,
  /** Релизы и обновления продукта — рассылается вручную. */
  RELEASES = 5,
}
